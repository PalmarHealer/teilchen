export const FALLBACK_PRODUCT_ICON = 'shopping-cart';

/** Upper case without umlauts, since eBons write either "KÄSE" or "KAESE". */
const normalise = (name: string) =>
	name
		.toUpperCase()
		.replace(/Ä/g, 'AE')
		.replace(/Ö/g, 'OE')
		.replace(/Ü/g, 'UE')
		.replace(/ß/g, 'SS');

export function productIcon(name: string): string {
	const n = normalise(name);
	return RULES.find(([re]) => re.test(n))?.[1] ?? FALLBACK_PRODUCT_ICON;
}

/** Every icon this module can return, so a test can check they all exist in @tabler/icons. */
export const PRODUCT_ICONS = [
	...new Set([...RULES.map(([, icon]) => icon), FALLBACK_PRODUCT_ICON])
];
